export function getEarningsForMonth(
  year: number,
  month: number,
): CorporateEarningsEvent[] {
  const prefix = `${year}-${String(month).padStart(2, "0")}`;
  return TOP_50_US_EARNINGS.filter((e) => e.date.startsWith(prefix));
}

export function groupEarningsByDate(
  events: CorporateEarningsEvent[],
): Record<string, CorporateEarningsEvent[]> {
  const res: Record<string, CorporateEarningsEvent[]> = {};
  for (const e of events) {
    if (!res[e.date]) {
      res[e.date] = [];
    }
    res[e.date].push(e);
  }
  return res;
}
